function envQuote(value) {
  const text = String(value ?? '')
  if (/\r|\n|\0/.test(text)) throw new YhtError('Environment values cannot contain control characters', { code: 'ENV_VALUE_INVALID' })
  return `"${text.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`
}

function sqlString(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'boolean') return value ? '1' : '0'
  if (/^(true|false)$/.test(String(value))) return String(value) === 'true' ? '1' : '0'
  return `'${String(value).replaceAll('\\', '\\\\').replaceAll("'", "''")}'`
}

function renderDeploySql(deployDatabase, compatibilityMode) {
  const statements = [
    '-- Generated by yhtctl. Values marked sensitive are never emitted in recommended mode.',
    'START TRANSACTION;',
  ]
  for (const [key, item] of Object.entries(deployDatabase).sort(([a], [b]) => a.localeCompare(b))) {
    if (item.sensitive) {
      if (compatibilityMode) statements.push(`-- compatibility-only sensitive key omitted from generated SQL: ${key}`)
      continue
    }
    if (item.authority !== 'deploy_db') continue
    statements.push(
      'INSERT INTO `system_deploy_config` '
      + '(`config_key`,`config_value`,`group_key`,`display_name`,`value_type`,`sensitive`,`client_visible`,`editable`,`remark`,`is_deleted`) '
      + `VALUES (${sqlString(key)},${sqlString(item.value)},'',${sqlString(key)},'string',0,0,1,'yhtctl profile override',0) `
      + 'ON DUPLICATE KEY UPDATE `config_value`=VALUES(`config_value`),`remark`=VALUES(`remark`),`is_deleted`=0;',
    )
  }
  statements.push('COMMIT;', '')
  return statements.join('\n')
}

function renderBrandSql(brandDatabase) {
  const entries = Object.entries(brandDatabase).sort(([a], [b]) => a.localeCompare(b))
  const columns = ['id', ...entries.map(([column]) => column)]
  const values = ['1', ...entries.map(([, value]) => sqlString(value))]
  const updates = entries.map(([column]) => `\`${column}\`=VALUES(\`${column}\`)`)
  return [
    '-- Generated public brand configuration. Contains no secrets.',
    'START TRANSACTION;',
    `INSERT INTO \`system_brand_config\` (${columns.map((column) => `\`${column}\``).join(',')})`,
    `VALUES (${values.join(',')})`,
    `ON DUPLICATE KEY UPDATE ${updates.join(',')};`,
    'COMMIT;',
    '',
  ].join('\n')
}

function serverName(url) {
  return new URL(url).hostname
}

function tlsLines(profile, authority) {
  if (profile.tls.mode !== 'existing-files') return ['  listen 80;']
  const cert = profile.tls.certificateRef.replace(/^file:\/\//, profile.deployment.paths.configRoot + '/')
  const keyRecord = authority.records.find((record) => record.profilePath === 'tls.privateKeySecretRef')
  if (!keyRecord) throw new YhtError('TLS private key secret was not materialized', { code: 'TLS_PRIVATE_KEY_MISSING' })
  const key = keyRecord.value
  return [
    '  listen 443 ssl http2;',
    `  ssl_certificate ${cert};`,
    `  ssl_certificate_key ${key};`,
  ]
}

function renderNginx(profile, authority) {
  const { endpoints, paths, ports } = profile.deployment
  const listen = tlsLines(profile, authority).join('\n')
  return `# Generated by yhtctl. Validate with nginx -t before reload.
server {
${listen}
  server_name ${serverName(endpoints.apiBaseUrl)};
  location / { proxy_pass http://127.0.0.1:${ports.api}; proxy_set_header Host $host; proxy_set_header X-Forwarded-Proto $scheme; }
}
server {
${listen}
  server_name ${serverName(endpoints.manageBaseUrl)};
  root ${paths.installRoot}/current/manage-admin;
  location / { try_files $uri $uri/ /index.html; }
}
server {
${listen}
  server_name ${serverName(endpoints.userBaseUrl)};
  root ${paths.installRoot}/current/pc-admin;
  location / { try_files $uri $uri/ /index.html; }
}
server {
${listen}
  server_name ${serverName(endpoints.h5BaseUrl)};
  root ${paths.installRoot}/current/h5;
  location / { try_files $uri $uri/ /index.html; }
}
server {
${listen}
  server_name ${serverName(endpoints.websiteBaseUrl)};
  location / { proxy_pass http://127.0.0.1:${ports.website}; proxy_set_header Host $host; proxy_set_header X-Forwarded-Proto $scheme; }
  location /customer-assets/ { alias ${paths.configRoot}/assets/; try_files $uri =404; }
}
`
}

