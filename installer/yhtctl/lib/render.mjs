function renderExternalActions(actions) {
  const lines = ['# External Actions', '', '| ID | Platform | State | Owner | Action | Verification |', '| --- | --- | --- | --- | --- | --- |']
  for (const action of actions) {
    const clean = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ')
    lines.push(`| ${clean(action.id)} | ${clean(action.platform)} | ${clean(action.state)} | ${clean(action.owner)} | ${clean(action.action)} | ${clean(action.verification)} |`)
  }
  lines.push('', 'Platform actions are separate from local installation acceptance. `user-final-required` is not a local pass.', '')
  return lines.join('\n')
}

export function renderConfiguration({ profile, authority, outputDir, sourceRoot = repoRoot, drift = null, authorizationFiles = {}, additionalEnvironment = {} }) {
  ensureDir(outputDir, 0o750)
  const compatibilityMode = profile.security.sensitiveDbCompatibilityMode
  const executables = {
    java: process.platform === 'linux' ? (resolveCommand('java') || '/usr/bin/java') : '/usr/bin/java',
    node: process.platform === 'linux' ? (resolveCommand('node') || '/usr/bin/node') : '/usr/bin/node',
  }
  const runtimeEnvironment = { ...authority.environment, ...additionalEnvironment }
  const environmentText = `${Object.entries(runtimeEnvironment)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([key, value]) => `${key}=${envQuote(value)}`)
    .join('\n')}\n`
  const outputs = {
    'runtime.env': { content: environmentText, mode: 0o600, sensitive: true },
    'system-deploy-config.sql': { content: renderDeploySql(authority.deployDatabase, compatibilityMode), mode: 0o640 },
    'brand-config.sql': { content: renderBrandSql(authority.brandDatabase), mode: 0o640 },
    'nginx/yihetong.conf': { content: renderNginx(profile, authority), mode: 0o640 },
    'systemd/yihetong-api.service': { content: renderApiService(profile, executables), mode: 0o640 },
    'systemd/yihetong-website.service': { content: renderWebsiteService(profile, executables), mode: 0o640 },
    'systemd/yihetong-license-refresh.service': { content: renderLicenseRefreshService(profile), mode: 0o640 },
    'systemd/yihetong-license-refresh.timer': { content: renderLicenseRefreshTimer(profile), mode: 0o640 },
    'build-inputs.env': {
      content: `${Object.entries(authority.buildInputs).sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => `${key}=${envQuote(value)}`).join('\n')}\n`,
      mode: 0o640,
    },
    'external-actions.md': { content: renderExternalActions(profile.externalActions), mode: 0o640 },
    ...authorizationFiles,
  }
  const applicationTemplate = path.join(sourceRoot, 'deploy', 'backend', 'application-template-prod.example.yml')
  if (existsSync(applicationTemplate)) {
    outputs['application.yml'] = { content: readFileSync(applicationTemplate, 'utf8'), mode: 0o640 }
  }
  for (const [relative, content] of Object.entries(authority.restrictedFiles || {})) {
    outputs[relative] = { content, mode: 0o600, sensitive: true }
  }
  const manifestEntries = []
  for (const [relative, descriptor] of Object.entries(outputs)) {
    const target = path.join(outputDir, ...relative.split('/'))
    atomicWrite(target, descriptor.content, descriptor.mode)
    manifestEntries.push({
      path: relative,
      bytes: Buffer.byteLength(descriptor.content, 'utf8'),
      sha256: sha256(descriptor.content),
      mode: descriptor.mode.toString(8).padStart(4, '0'),
      sensitive: Boolean(descriptor.sensitive),
    })
  }
  const plan = {
    apiVersion: 'yht.io/v1',
    kind: 'RenderedConfigurationPlan',
    customerCode: profile.metadata.customerCode,
    profileRevision: profile.metadata.profileRevision,
    profileFingerprint: sha256Object(profile),
    authorityFingerprint: authority.authorityFingerprint,
    sensitiveDbCompatibilityMode: compatibilityMode,
    additionalEnvironmentKeys: Object.keys(additionalEnvironment).sort(),
    runtimeExecutables: executables,
    providerScope: ['aliyun-oss'],
    records: authority.records.map(redactRecord),
    drift,
    outputs: manifestEntries,
  }
  plan.planDigest = sha256Object(plan)
  atomicWrite(path.join(outputDir, 'CONFIG_PLAN.json'), canonicalJson(plan), 0o640)
  manifestEntries.push({
    path: 'CONFIG_PLAN.json',
    bytes: Buffer.byteLength(canonicalJson(plan), 'utf8'),
    sha256: sha256(canonicalJson(plan)),
    mode: '0640',
    sensitive: false,
  })
  atomicWrite(path.join(outputDir, 'RENDER_MANIFEST.json'), canonicalJson({ version: 1, files: manifestEntries }), 0o640)
  return { plan, manifestEntries, outputDir: path.resolve(outputDir) }
}
